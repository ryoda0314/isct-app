// Regenerate the local, texture-free city blocks from an OSM Map API XML extract.
// Bounds used: 139.7585,35.6975,139.7700,35.7060. Attribution is shown in both maps.
import fs from "node:fs/promises";
import xml2js from "xml2js";
import { inside, boundsOf } from "../campus-sns/yokohama/navigation.js";

const {osm}=await xml2js.parseStringPromise(await fs.readFile(process.argv[2]));
const round=n=>Math.round(n*10)/10;
const nodes=new Map(osm.node.map(({$:n})=>[n.id,[round((n.lon-139.7645)*90499),round((35.7017-n.lat)*110952)]]));
const features=osm.way.map(w=>({
  id:Number(w.$.id), ring:w.nd.map(n=>nodes.get(n.$.ref)).filter(Boolean),
  tags:Object.fromEntries((w.tag||[]).map(t=>[t.$.k,t.$.v])),
}));
const campus=features.find(w=>w.id===52980054).ring;
// PLATEAU Bunkyo 2025 LOD1 features, projected into the same local frame.
// Restrict matching to footprints with both a close centre and similar extents.
const surveyed=process.argv[3]?Object.values(JSON.parse(await fs.readFile(process.argv[3],"utf8"))):[];
function measuredHeight(ring,center,w,d) {
  let best=null,score=.65;
  for(const f of surveyed) {
    if(!(f.h>2)||Math.hypot(center[0]-f.pos[0],center[1]-f.pos[1])>Math.max(3,Math.min(w,d)*.24))continue;
    if(!inside(f.pos,ring))continue;
    const dx=Math.max(0,Math.min(center[0]+w/2,f.max[0])-Math.max(center[0]-w/2,f.min[0]));
    const dz=Math.max(0,Math.min(center[1]+d/2,f.max[1])-Math.max(center[1]-d/2,f.min[1]));
    const overlap=dx*dz/(w*d+(f.max[0]-f.min[0])*(f.max[1]-f.min[1])-dx*dz);
    if(overlap>score) {best=f;score=overlap;}
  }
  return best;
}
const blocks=[],streets=[],groves=[];
const temples=new Set([91528891,230824890,230824892,230824893,230824895]);
const widths={primary:16,secondary:12,tertiary:9,residential:5.4,unclassified:6,living_street:4,service:3.5};
for(const {ring,tags,id} of features) {
  if(ring.length<2)continue;
  const {center:[x,z],width,depth}=boundsOf(ring);
  const distance=Math.hypot(x/405,(z-25)/345);
  if(tags.building && ring.length>3 && id!==143820280) {
    if(inside([x,z],campus) || distance>1.8)continue;
    const outline=ring.slice(0,-1);
    if(outline.length<3 || width<1 || depth<1 || ["roof","carport","bridge","construction"].includes(tags.building))continue;
    const parsedHeight=parseFloat(tags.height),levels=parseFloat(tags["building:levels"]);
    const house=["house","detached","hut","garage","shed"].includes(tags.building);
    const fallback=house ? 6.3 : Math.min(24,Math.max(6.4,Math.sqrt(width*depth)*.70));
    const measured=measuredHeight(outline,[x,z],width,depth);
    const height=round(measured?.h??(parsedHeight>0?parsedHeight:levels>0?levels*3.25:fallback));
    const style=temples.has(id)?"seido":tags.building==="shrine"||tags.building==="gatehouse"?"shrine":house?"house":"city";
    blocks.push(measured?[id,height,style,outline,measured.id]:[id,height,style,outline]);
  }
  if(widths[tags.highway] && tags.tunnel!=="yes" && !tags.bridge && distance<1.8 && !inside([x,z],campus)) {
    streets.push([id,widths[tags.highway],ring]);
  }
  if((tags.natural==="wood" || tags.landuse==="forest" || tags.leisure==="park" || id===46985717) && distance<1.1 && ring.length>3) {
    groves.push([id,ring.slice(0,-1)]);
  }
}
const js=(name,rows)=>`export const ${name}=[\n${rows.map(row=>JSON.stringify(row)).join(",\n")}\n];\n`;
await fs.mkdir(new URL("../campus-sns/yushima/",import.meta.url),{recursive:true});
await fs.writeFile(new URL("../campus-sns/yushima/neighbourhoodData.js",import.meta.url),
  "// © OpenStreetMap contributors, ODbL. Generated by scripts/gen-campus-yushima-context.mjs.\n"+
  js("blocks",blocks)+js("streets",streets)+js("groves",groves));
console.log({blocks:blocks.length,measured:blocks.filter(row=>row[4]).length,streets:streets.length,groves:groves.length});
