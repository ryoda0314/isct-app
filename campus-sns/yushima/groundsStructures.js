const dist=(a,b)=>Math.hypot(a[0]-b[0],a[1]-b[1]);
const xyz=(p,h)=>[p[0],h,p[1]];
export function cap(T,batch,ring,height,color,holes=[]) {
  const at=typeof height==='function'?height:()=>height;
  const vectors=points=>points.map(p=>new T.Vector2(...p));
  const faces=T.ShapeUtils.triangulateShape(vectors(ring),holes.map(vectors));
  const all=[...ring,...holes.flat()];
  for(const face of faces)batch.tri(...face.map(i=>xyz(all[i],at(...all[i]))),color);
}
export function garden(T,group,t,batch,pavers) {
  const h=gardenLevel,parkWall=0xa7aaa9,panels=[];
  plantRoof(T,group,t,batch,pavers,cap,garageFootprint,h);
  for(let i=0;i<garageFootprint.length;i++) {
    const a=garageFootprint[i],b=garageFootprint[(i+1)%garageFootprint.length],baseA=groundHeight(...a)-.5,baseB=groundHeight(...b)-.5;
    const count=Math.ceil(dist(a,b)/3.2);
    for(let j=0;j<count;j++){
      const u=interpolate(a,b,j/count),v=interpolate(a,b,(j+1)/count),floorU=baseA+(baseB-baseA)*j/count,floorV=baseA+(baseB-baseA)*(j+1)/count;
      t.quad(xyz(u,floorU),xyz(v,floorV),xyz(v,h-.3),xyz(u,h-.3),0x59646a);
      t.quad(xyz(u,h-.88),xyz(v,h-.88),xyz(v,h+.08),xyz(u,h+.08),parkWall);
      batch.beam(xyz(u,floorU),xyz(u,h-.45),.34,.45,0xbfc2bd);
      for(const d of [1.05,1.38,1.71,3.45,3.76]) {
        if(h-d<Math.max(floorU,floorV)+.1)continue;
        batch.beam(xyz(u,h-d),xyz(v,h-d),.17,.15,0x9da49f);
      }
    }
    // Garden visitors arrive from the pedestrian bridge on the northeast side.
    if(i===0) {
      const L=interpolate(a,b,.82),R=interpolate(a,b,.93);
      panels.push([a,L],[R,b]);
    }else panels.push([a,b]);
  }
  wirePanels(T,group,batch,panels,h);
  const [sx,sz]=[-87,37.3];
  sundial(T,group,t,batch,h,sx,sz);
  addBlocker([sx,sz],[sx,sz],.45);
}

// Small vector lettering generated by the app. The text has its own solid sign board.
function sign(T,group,label,sub,p,width,height,rotation,ink='#243f4d',background='#edeee8') {
  if(typeof document==='undefined')return;
  const canvas=document.createElement('canvas');canvas.width=768;canvas.height=Math.round(768*height/width);
  const ctx=canvas.getContext('2d');if(!ctx)return;
  ctx.fillStyle=background;ctx.fillRect(0,0,canvas.width,canvas.height);
  ctx.fillStyle=ink;ctx.textBaseline='middle';ctx.textAlign='center';
  ctx.font='bold '+Math.round(canvas.height*(sub?.39:.55))+'px "Yu Gothic",sans-serif';
  ctx.fillText(label,384,canvas.height*(sub?.38:.5),708);
  if(sub){ctx.font=Math.round(canvas.height*.17)+'px sans-serif';ctx.fillText(sub,384,canvas.height*.77,695);}
  const texture=new T.CanvasTexture(canvas);texture.colorSpace=T.SRGBColorSpace;
  const panel=new T.Mesh(new T.PlaneGeometry(width,height),new T.MeshBasicMaterial({map:texture,side:T.DoubleSide}));
  panel.position.set(...p);panel.rotation.y=rotation;panel.name=label;group.add(panel);
}
export function gateFurniture(T,group,batch) {
  for(const g of gates){
    const [x,z]=g.point;
    const angle=['yushima-gate','north-gate','hongo-gate'].includes(g.id)?-.67:g.id==='west-gate'||g.id==='sotobori-1'?1.08:g.id==='hijiri-gate'?1.23:g.id==='sotobori-2'?-.93:-.39;
    const tangent=[Math.cos(angle),-Math.sin(angle)],normal=[Math.sin(angle),Math.cos(angle)];
    const size=['yushima-gate','ochanomizu-gate'].includes(g.id)?4.6:3.15;
    for(const side of [-1,1]){
      let u=x+side*size*tangent[0],v=z+side*size*tangent[1];
      for(const shift of [0,1.2,-1.2,2.4,-2.4,3.8,-3.8]) {
        const a=x+side*size*tangent[0]+normal[0]*shift,b=z+side*size*tangent[1]+normal[1]*shift;
        if(clearanceFromWalk(a,b)>1.4){u=a;v=b;break;}
      }
      const y=roadTerrainHeight(u,v),major=side===-1;
      batch.put('box',0x939796,u,y+.11,v,major?2.3:1.1,.22,.89,angle);
      batch.put('box',major?0x858783:0x9a9c97,u,y+.79,v,major?2.2:.97,1.39,.71,angle);
      batch.put('box',0xb3b1a7,u,y+1.52,v,major?2.28:1.04,.1,.81,angle);
      addBlocker([u,v],[u,v],.48);
      if(major)sign(T,group,g.name,'東京科学大学',[u+normal[0]*.36,y+.95,v+normal[1]*.36],1.6,.53,angle);
    }
  }
}
export function bridges(T,group,t,batch,pavers) {
  ochanomizuBridge(t,batch,pavers,(name,position,width,height,rotation)=>{
    sign(T,group,name,'',position,width,height,rotation,'#d2cbb3','#68695f');
  });
  {
    const id='hijiri',b=bridgeSpecs.hijiri;
    const [a,c]=[b.start,b.end],len=dist(a,c),nx=-(c[1]-a[1])/len,nz=(c[0]-a[0])/len;
    const pos=(u,s,lift=0)=>{const x=a[0]+(c[0]-a[0])*u+nx*s,z=a[1]+(c[1]-a[1])*u+nz*s;return [x,bridgeLevel(id,x,z)+lift,z];};
    pavers.orient(c[0]-a[0],c[1]-a[1]);
    const half=b.width/2;
    for(let i=0;i<72;i++){
      const f=i/72,g=(i+1)/72;
      t.quad(pos(f,-half),pos(g,-half),pos(g,half),pos(f,half),0x767e82);
      for(const side of [-1,1]){
        const inner=side*(half-3.2),outer=side*half;
        pavers.quad(pos(f,inner,.11),pos(g,inner,.11),pos(g,outer,.11),pos(f,outer,.11),0xada998);
        t.quad(pos(f,inner,.13),pos(g,inner,.13),pos(g,inner-.15*side,.13),pos(f,inner-.15*side,.13),0xc1bcac);
        const underside=u=>{
          if(u<.245||u>.704)return -1.3;
          const curve=(u-.475)/.198;
          return -1.65-10.7*(1-Math.sqrt(Math.max(0,1-curve*curve)));
        };
        t.quad(pos(f,outer,.18),pos(g,outer,.18),pos(g,outer,underside(g)),pos(f,outer,underside(f)),0xc5c2ad);
        t.quad(pos(f,outer,underside(f)),pos(g,outer,underside(g)),pos(g,outer-side*.68,underside(g)),pos(f,outer-side*.68,underside(f)),0xacae9f);
        if(f>.28&&g<.67) {
          // Moulded archivolt follows the intrados of the concrete arch.
          batch.beam(pos(f,outer+.04*side,underside(f)+.25),pos(g,outer+.04*side,underside(g)+.25),.26,.22,0xd0cdb7);
        }
        if(i%4===0){
          batch.beam(pos(f,outer,.16),pos(f,outer,1.24),.32,.32,0xb6b39d);
        }
        batch.beam(pos(f,outer,1.24),pos(g,outer,1.24),.23,.15,0xbab69f);
        for(const level of [.49,.82]) batch.beam(pos(f,outer,level),pos(g,outer,level),.057,.052,0x85897c);
        if(i%2===0)batch.beam(pos(f,outer,.29),pos(f,outer,1.14),.06,.07,0x798777);
      }
      if(i%12<7)t.quad(pos(f,-.06,.02),pos(g,-.06,.02),pos(g,.06,.02),pos(f,.06,.02),0xe5e2cb);
    }
    for (const f of [.045,.95]) for (const side of [-1,1]){
      const foot=pos(f,(half-.5)*side,.18),p=pos(f,(half-.5)*side,4.3);
      batch.beam(foot,p,.15,.15,0x6e7570,'post');
      batch.put('round',0xd6dbce,p[0],p[1]+.27,p[2],.23,.38,.23);
    }
  }
}
export function station(T,group,t,batch) {
  const railY=groundHeight(73,244)-.35;
  // Chain the three surveyed segments of the riverside platform track.
  chuoRapid(batch,[...rails[16],...rails[9].slice(1),...rails[21].slice(1)],railY);
  for(const way of rails)for(let i=1;i<way.length;i++){
    const a=way[i-1],b=way[i],len=dist(a,b),nx=-(b[1]-a[1])/len,nz=(b[0]-a[0])/len;
    const p=(f,s,lift)=>[a[0]+(b[0]-a[0])*f+nx*s,railY+lift,a[1]+(b[1]-a[1])*f+nz*s];
    t.quad(p(0,-1.7,0),p(1,-1.7,0),p(1,1.7,0),p(0,1.7,0),0x857e71);
    for(const side of [-.534,.534])batch.beam(p(0,side,.14),p(1,side,.14),.10,.12,0x646b6b);
    for(let j=0;j<Math.ceil(len/1.2);j++)batch.beam(p((j+.5)/Math.ceil(len/1.2),-1.07,.045),p((j+.5)/Math.ceil(len/1.2),1.07,.045),.19,.1,0x776e5f);
  }
  for(const ring of platforms){
    cap(T,t,ring,railY+1.1,0xc0bbb0);cap(T,t,ring,railY+4.75,0xa0a7a5);
    const [a,b]=[ring[0],ring[4]];
    for(let j=0;j<14;j++) {
      const p=interpolate(a,b,(j+.25)/14);batch.beam(xyz(p,railY+.3),xyz(p,railY+4.7),.25,.3,0x697472);
    }
    ring.forEach((a,i)=>{const b=ring[(i+1)%ring.length];t.quad(xyz(a,railY+.1),xyz(b,railY+.1),xyz(b,railY+1.1),xyz(a,railY+1.1),0x7f817f);batch.beam(xyz(a,railY+4.65),xyz(b,railY+4.65),.15,.24,0x929d9d);});
  }
  const upperY=bridgeSpecs.ochanomizu.south;
  stationRiverFront(t,batch,upperY);
  cap(T,t,stationOutline,upperY+3.2,0xbabdb8);
  cap(T,t,stationOutline,upperY-.62,0xb6b4a9);
  for(let i=0;i<stationOutline.length;i++){
    const a=stationOutline[i],b=stationOutline[(i+1)%stationOutline.length],run=dist(a,b);
    t.quad(xyz(a,upperY+2.55),xyz(b,upperY+2.55),xyz(b,upperY+3.19),xyz(a,upperY+3.19),0x9ba6a5);
    t.quad(xyz(a,upperY-.61),xyz(b,upperY-.61),xyz(b,upperY-.99),xyz(a,upperY-.99),0xa4a69c);
    for(let j=0;j<Math.ceil(run/4);j++){const q=interpolate(a,b,j/Math.ceil(run/4));batch.beam(xyz(q,railY+.2),xyz(q,upperY+2.59),.21,.26,0x849392);}
  }
  stationPortal(batch,upperY,(...args)=>sign(T,group,...args));
  // The vermilion box-girder Marunouchi Line bridge runs diagonally through the river cutting.
  const a=[139.4,210.5],b=[184.5,255.9],y=waterLevel+5.05;
  const dx=(b[0]-a[0])/dist(a,b),dz=(b[1]-a[1])/dist(a,b);
  for(const s of [-2.65,0,2.65]){
    const side=p=>[p[0]-s*dz,y,p[1]+s*dx];
    batch.beam(side(a),side(b),s?.44:1.1,s?1.18:.48,0xae523c);
    if(s)for(let f=0;f<=30;f++){const q=side(interpolate(a,b,f/30));batch.beam(q,[q[0],y+1.1,q[2]],.045,.07,0xa2664c);}
    if(s){const u=side(a),v=side(b);u[1]+=1.1;v[1]+=1.1;batch.beam(u,v,.08,.07,0xa6644a);}
  }
  for(const cross of [.1,.91]){const q=interpolate(a,b,cross);batch.put('box',0xa3a29a,q[0],waterLevel+2,q[1],6.1,4.05,1.1,-Math.atan2(dx,dz));}
}




